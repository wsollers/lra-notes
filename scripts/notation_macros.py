"""Generate generated/lean/notation.tex from the lra-governance notation registry.

The Lean exporter writes semantic macros such as \\leanReal; this script defines
them from `notation.yaml`, so notation is owned by the registry and never by
lra-notes. A macro whose registry entry is missing is a hard error.

Usage: python scripts/notation_macros.py [--governance PATH] [--out PATH]

Governance is resolved like AGENTS.md: --governance, then LRA_GOVERNANCE_ROOT,
then the sibling ../lra-governance.
"""
from __future__ import annotations

import argparse
import os
import pathlib
import sys

import yaml

# exporter macro -> notation registry id
MACROS = {
    "leanNat": "not:natural-numbers",
    "leanInt": "not:integers",
    "leanRat": "not:rational-numbers",
    "leanReal": "not:real-numbers",
    "leanComplex": "not:complex-numbers",
}


def governance_root(explicit: str | None, repo: pathlib.Path) -> pathlib.Path:
    candidates = [explicit, os.environ.get("LRA_GOVERNANCE_ROOT"), str(repo.parent / "lra-governance")]
    for c in candidates:
        if c and (pathlib.Path(c) / "notation.yaml").is_file():
            return pathlib.Path(c)
    sys.exit("notation_macros: lra-governance is not present (set LRA_GOVERNANCE_ROOT)")


def main() -> None:
    repo = pathlib.Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser()
    ap.add_argument("--governance")
    ap.add_argument("--out", default=str(repo / "generated" / "lean" / "notation.tex"))
    args = ap.parse_args()

    gov = governance_root(args.governance, repo)
    entries = yaml.safe_load((gov / "notation.yaml").read_text(encoding="utf-8"))["notation"]
    by_id = {e["id"]: e for e in entries}

    missing = [nid for nid in MACROS.values() if nid not in by_id]
    if missing:
        sys.exit(f"notation_macros: registry has no entry for {', '.join(missing)}")

    lines = [
        "% GENERATED by scripts/notation_macros.py from lra-governance/notation.yaml.",
        "% Do not edit; change the registry instead.",
    ]
    for macro, nid in MACROS.items():
        lines.append(f"\\providecommand{{\\{macro}}}{{{by_id[nid]['symbol']}}}  % {nid}")

    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"notation_macros: wrote {len(MACROS)} macros to {out}")


if __name__ == "__main__":
    main()
